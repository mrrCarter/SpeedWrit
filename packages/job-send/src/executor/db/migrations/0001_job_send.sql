-- Job-bound sending: the spec's tables ("Data model and invariants").
--
-- Invariants the database itself enforces, so a code path that forgets one still cannot break it:
--   1. a proposal version is immutable after insert; only `state` may change (trigger);
--   2. at most one approval and one dispatch per version (UNIQUE proposal_version_id on both);
--   3. sends_reserved stays between 0 and max_sends (CHECK);
--   receipts are append-only (triggers refuse UPDATE, DELETE and TRUNCATE) and each owner's
--   receipt sequence has no duplicates (UNIQUE owner_id, seq).
-- Lock order everywhere (code, not schema): proposal, version, job, connection, then the version's dispatch,
-- then the owner's receipt counter.
--
-- Ids are text with a type prefix, generated by the application. Timestamps are timestamptz (UTC).

CREATE TABLE owners (
  id           text PRIMARY KEY,
  google_sub   text NOT NULL UNIQUE,
  email        text NOT NULL,
  -- The per-owner receipt counter. writeReceipt increments it under the row lock, inside the
  -- transaction of the change it records, so a rollback takes the number back: no gaps.
  receipt_seq  integer NOT NULL DEFAULT 0 CHECK (receipt_seq >= 0),
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE connections (
  id                 text PRIMARY KEY,
  owner_id           text NOT NULL REFERENCES owners (id),
  provider           text NOT NULL CHECK (provider IN ('gmail')),
  account_email      text NOT NULL,
  -- Token custody envelope ("v1." + base64url); NULL once the token is deleted on disconnect.
  refresh_token_enc  text CHECK (refresh_token_enc IS NULL OR refresh_token_enc LIKE 'v1.%'),
  dispatch_enabled   boolean NOT NULL DEFAULT true,
  status             text NOT NULL DEFAULT 'active'
                     CHECK (status IN ('active', 'stopped', 'revoked', 'needs_reconnect')),
  created_at         timestamptz NOT NULL DEFAULT now(),
  -- The target of jobs' (connection_id, owner_id) key.
  UNIQUE (id, owner_id)
);

CREATE TABLE agent_connections (
  id            text PRIMARY KEY,
  owner_id      text NOT NULL REFERENCES owners (id),
  client_id     text NOT NULL,
  client_label  text NOT NULL,
  revoked_at    timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  -- The target of jobs' (agent_connection_id, owner_id) key.
  UNIQUE (id, owner_id)
);

-- OAuth for the agent connection (contract lane). Hashes only at rest.
CREATE TABLE oauth_clients (
  client_id      text PRIMARY KEY,
  client_name    text,
  redirect_uris  text[] NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE oauth_codes (
  code_hash            text PRIMARY KEY,
  client_id            text NOT NULL REFERENCES oauth_clients (client_id),
  agent_connection_id  text NOT NULL REFERENCES agent_connections (id),
  redirect_uri         text NOT NULL,
  code_challenge       text NOT NULL,
  resource             text NOT NULL,
  scope                text NOT NULL,
  expires_at           timestamptz NOT NULL,
  used_at              timestamptz
);

CREATE TABLE access_tokens (
  token_hash           text PRIMARY KEY,
  agent_connection_id  text NOT NULL REFERENCES agent_connections (id),
  resource             text NOT NULL,
  scope                text NOT NULL,
  expires_at           timestamptz NOT NULL,
  revoked_at           timestamptz
);

CREATE TABLE refresh_tokens (
  token_hash           text PRIMARY KEY,
  client_id            text NOT NULL REFERENCES oauth_clients (client_id),
  agent_connection_id  text NOT NULL REFERENCES agent_connections (id),
  resource             text NOT NULL,
  scope                text NOT NULL,
  expires_at           timestamptz NOT NULL,
  rotated_at           timestamptz,
  revoked_at           timestamptz
);

CREATE TABLE contacts (
  id            text PRIMARY KEY,
  owner_id      text NOT NULL REFERENCES owners (id),
  email         text NOT NULL CHECK (email = lower(email)),
  name          text NOT NULL,
  client_label  text,
  UNIQUE (owner_id, email)
);

CREATE TABLE templates (
  id           text PRIMARY KEY,
  owner_id     text REFERENCES owners (id),
  subject_tpl  text NOT NULL,
  body_tpl     text NOT NULL,
  fields       jsonb NOT NULL DEFAULT '[]',
  sha256       text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$')
);

CREATE TABLE jobs (
  id                          text PRIMARY KEY,
  owner_id                    text NOT NULL REFERENCES owners (id),
  connection_id               text NOT NULL,
  agent_connection_id         text NOT NULL,
  purpose                     text NOT NULL DEFAULT '',
  recipient_email             text NOT NULL CHECK (recipient_email = lower(recipient_email)),
  template_id                 text NOT NULL REFERENCES templates (id),
  template_sha256             text NOT NULL CHECK (template_sha256 ~ '^[0-9a-f]{64}$'),
  field_rules                 jsonb NOT NULL DEFAULT '{}',
  max_sends                   integer NOT NULL CHECK (max_sends >= 1),
  sends_reserved              integer NOT NULL DEFAULT 0,
  expires_at                  timestamptz NOT NULL,
  auto_send                   boolean NOT NULL DEFAULT false,
  allow_custom_with_approval  boolean NOT NULL DEFAULT false,
  ai_review                   text NOT NULL DEFAULT 'custom_only'
                              CHECK (ai_review IN ('off', 'custom_only', 'all_free_text')),
  policy_version              integer NOT NULL DEFAULT 1 CHECK (policy_version >= 1),
  status                      text NOT NULL DEFAULT 'draft'
                              CHECK (status IN ('draft', 'active', 'stopped', 'expired')),
  created_at                  timestamptz NOT NULL DEFAULT now(),
  -- A job binds only its own owner's connections. On another owner's Gmail connection it would send
  -- as that person, and the job owner's STOP would not stop it.
  CONSTRAINT jobs_connection_is_owners FOREIGN KEY (connection_id, owner_id) REFERENCES connections (id, owner_id),
  CONSTRAINT jobs_agent_connection_is_owners FOREIGN KEY (agent_connection_id, owner_id) REFERENCES agent_connections (id, owner_id),
  -- Invariant 3. The reservation's conditional UPDATE keeps it; this refuses any path that does not.
  CONSTRAINT jobs_sends_reserved_within_max CHECK (sends_reserved BETWEEN 0 AND max_sends)
);

-- A job's template is a shared one (owner_id NULL) or the job owner's own, never another owner's
-- private wording. A foreign key cannot say "NULL or mine", so a trigger does.
CREATE FUNCTION jobs_template_is_owners() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM templates t WHERE t.id = NEW.template_id AND t.owner_id IS NOT NULL AND t.owner_id <> NEW.owner_id) THEN
    RAISE EXCEPTION 'a job may use only a shared template or its owner''s own' USING ERRCODE = 'foreign_key_violation';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER jobs_template_is_owners BEFORE INSERT OR UPDATE OF template_id, owner_id ON jobs
  FOR EACH ROW EXECUTE FUNCTION jobs_template_is_owners();

CREATE TABLE attempts (
  id                   text PRIMARY KEY,
  job_id               text REFERENCES jobs (id),
  agent_connection_id  text NOT NULL REFERENCES agent_connections (id),
  tool                 text NOT NULL,
  args_sha256          text NOT NULL CHECK (args_sha256 ~ '^[0-9a-f]{64}$'),
  decision             text NOT NULL,
  reason_code          text,
  created_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX attempts_recent_denials ON attempts (agent_connection_id, job_id, created_at)
  WHERE decision = 'denied';

CREATE TABLE proposals (
  id               text PRIMARY KEY,
  job_id           text NOT NULL REFERENCES jobs (id),
  operation_id     text,
  current_version  integer NOT NULL DEFAULT 1 CHECK (current_version BETWEEN 1 AND 5),
  status           text NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('pending', 'dispatching', 'accepted', 'not_sent', 'unknown', 'rejected')),
  created_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (job_id, operation_id)
);

CREATE TABLE proposal_versions (
  id              text PRIMARY KEY,
  proposal_id     text NOT NULL REFERENCES proposals (id),
  version         integer NOT NULL CHECK (version BETWEEN 1 AND 5),
  recipient       text NOT NULL,
  subject         text NOT NULL,
  body            text NOT NULL,
  mime            bytea NOT NULL,
  canonical       jsonb NOT NULL,
  sha256          text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  policy_version  integer NOT NULL CHECK (policy_version >= 1),
  review_reasons  text[] NOT NULL DEFAULT '{}',
  state           text NOT NULL DEFAULT 'pending'
                  CHECK (state IN ('pending', 'superseded', 'rejected', 'dispatched')),
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (proposal_id, version)
);

-- Invariant 1: everything but `state` is fixed at insert, and a version is never deleted.
CREATE FUNCTION proposal_versions_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'proposal_versions rows are never deleted' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  IF (NEW.id, NEW.proposal_id, NEW.version, NEW.recipient, NEW.subject, NEW.body, NEW.mime,
      NEW.canonical, NEW.sha256, NEW.policy_version, NEW.review_reasons, NEW.created_at)
     IS DISTINCT FROM
     (OLD.id, OLD.proposal_id, OLD.version, OLD.recipient, OLD.subject, OLD.body, OLD.mime,
      OLD.canonical, OLD.sha256, OLD.policy_version, OLD.review_reasons, OLD.created_at) THEN
    RAISE EXCEPTION 'a proposal version is immutable after insert; only state may change'
      USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER proposal_versions_immutable BEFORE UPDATE OR DELETE ON proposal_versions
  FOR EACH ROW EXECUTE FUNCTION proposal_versions_immutable();

CREATE TABLE approvals (
  id                   text PRIMARY KEY,
  -- Invariant 2: one approval per version.
  proposal_version_id  text NOT NULL UNIQUE REFERENCES proposal_versions (id),
  version_sha256       text NOT NULL CHECK (version_sha256 ~ '^[0-9a-f]{64}$'),
  approver             text NOT NULL REFERENCES owners (id),
  created_at           timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE dispatches (
  id                   text PRIMARY KEY,
  -- Invariant 2: one dispatch per version. A second reservation fails here.
  proposal_version_id  text NOT NULL UNIQUE REFERENCES proposal_versions (id),
  -- 'auto', or the id of the approval that reserved it.
  via                  text NOT NULL,
  status               text NOT NULL DEFAULT 'reserved'
                       CHECK (status IN ('reserved', 'accepted', 'not_sent', 'unknown')),
  provider_message_id  text,
  error_class          text,
  -- The owner's attestation on an UNKNOWN outcome: 'seen' (witnessed) or 'not_arrived'.
  witness              text CHECK (witness IS NULL OR witness IN ('seen', 'not_arrived')),
  resolved_by          text REFERENCES owners (id),
  resolved_at          timestamptz,
  reserved_at          timestamptz NOT NULL,
  finished_at          timestamptz,
  CHECK (status <> 'accepted' OR provider_message_id IS NOT NULL),
  CHECK (witness IS NULL OR status = 'unknown')
);
CREATE INDEX dispatches_still_reserved ON dispatches (reserved_at) WHERE status = 'reserved';

CREATE TABLE receipts (
  id          text PRIMARY KEY,
  owner_id    text NOT NULL REFERENCES owners (id),
  seq         integer NOT NULL CHECK (seq >= 1),
  type        text NOT NULL CHECK (type IN (
                'CONNECTION_CREATED', 'AGENT_CONNECTED', 'JOB_CONFIRMED', 'ATTEMPT_DENIED',
                'PROPOSAL_CREATED', 'PROPOSAL_REVISED', 'AI_REVIEW', 'APPROVAL_GRANTED',
                'APPROVAL_REJECTED', 'APPROVAL_REFUSED', 'DISPATCH_RESERVED', 'DISPATCH_REFUSED',
                'PROVIDER_ACCEPTED', 'NOT_SENT', 'OUTCOME_UNKNOWN', 'OUTCOME_RESOLVED',
                'DELIVERY_WITNESSED', 'STOP_ENGAGED', 'PROVIDER_REVOKE_REQUESTED',
                'PROVIDER_REVOKE_RESULT')),
  -- The JCS text, byte for byte as signed.
  payload     text NOT NULL,
  signature   text NOT NULL,
  key_id      text NOT NULL CHECK (key_id ~ '^[0-9a-f]{16}$'),
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (owner_id, seq)
);

-- Receipts are append-only.
CREATE FUNCTION receipts_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'receipts are append-only (% refused)', TG_OP USING ERRCODE = 'integrity_constraint_violation';
END
$$;
CREATE TRIGGER receipts_append_only BEFORE UPDATE OR DELETE ON receipts
  FOR EACH ROW EXECUTE FUNCTION receipts_append_only();
CREATE TRIGGER receipts_no_truncate BEFORE TRUNCATE ON receipts
  FOR EACH STATEMENT EXECUTE FUNCTION receipts_append_only();
